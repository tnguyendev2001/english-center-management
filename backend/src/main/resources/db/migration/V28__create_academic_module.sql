    PRIMARY KEY (id),
    CONSTRAINT fk_learning_materials_classroom FOREIGN KEY (classroom_id) REFERENCES classrooms (id),
    CONSTRAINT fk_learning_materials_lesson FOREIGN KEY (lesson_record_id) REFERENCES lesson_records (id),
    CONSTRAINT fk_learning_materials_assignment FOREIGN KEY (assignment_id) REFERENCES assignments (id),
    CONSTRAINT fk_learning_materials_assessment FOREIGN KEY (assessment_id) REFERENCES assessments (id)
