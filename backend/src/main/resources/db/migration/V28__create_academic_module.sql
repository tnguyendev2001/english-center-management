CREATE INDEX idx_learning_materials_classroom_id ON learning_materials (classroom_id);
CREATE INDEX idx_learning_materials_lesson_id ON learning_materials (lesson_record_id);
CREATE INDEX idx_learning_materials_assignment_id ON learning_materials (assignment_id);
CREATE INDEX idx_learning_materials_assessment_id ON learning_materials (assessment_id);
CREATE INDEX idx_learning_materials_active ON learning_materials (active);

