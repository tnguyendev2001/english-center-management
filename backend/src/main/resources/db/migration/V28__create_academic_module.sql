-- Phase 11: Learning content, assignments, assessments, evaluations, progress reports

CREATE TABLE evaluation_periods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(200) NOT NULL,
    classroom_id BIGINT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    reopen_reason VARCHAR(1000) NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_evaluation_periods_classroom FOREIGN KEY (classroom_id) REFERENCES classrooms (id),
    CONSTRAINT chk_evaluation_periods_dates CHECK (start_date <= end_date)
);

CREATE INDEX idx_evaluation_periods_classroom_id ON evaluation_periods (classroom_id);
CREATE INDEX idx_evaluation_periods_status ON evaluation_periods (status);
CREATE INDEX idx_evaluation_periods_dates ON evaluation_periods (start_date, end_date);

CREATE TABLE lesson_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    class_session_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    objectives TEXT NULL,
    planned_content TEXT NULL,
    actual_content TEXT NULL,
    vocabulary TEXT NULL,
    grammar_topics TEXT NULL,
    skills TEXT NULL,
    homework_instruction TEXT NULL,
    teacher_note TEXT NULL,
    status VARCHAR(20) NOT NULL,
    created_by VARCHAR(100) NULL,
    created_at TIMESTAMP NOT NULL,
    updated_by VARCHAR(100) NULL,
    updated_at TIMESTAMP NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT fk_lesson_records_session FOREIGN KEY (class_session_id) REFERENCES class_sessions (id),
    CONSTRAINT uk_lesson_records_session UNIQUE (class_session_id)
);

CREATE INDEX idx_lesson_records_status ON lesson_records (status);

CREATE TABLE assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR(255) NOT NULL,
    description TEXT NULL,
    instructions TEXT NULL,
    classroom_id BIGINT NOT NULL,
    lesson_record_id BIGINT NULL,
    assigned_date DATE NOT NULL,
    due_date DATE NULL,
    max_score NUMERIC(19, 2) NULL,
    allow_submission BOOLEAN NOT NULL DEFAULT TRUE,
    allow_late_submission BOOLEAN NOT NULL DEFAULT FALSE,
    target_mode VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_by_teacher_id BIGINT NULL,
    created_by VARCHAR(100) NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT fk_assignments_classroom FOREIGN KEY (classroom_id) REFERENCES classrooms (id),
    CONSTRAINT fk_assignments_lesson FOREIGN KEY (lesson_record_id) REFERENCES lesson_records (id),
    CONSTRAINT fk_assignments_teacher FOREIGN KEY (created_by_teacher_id) REFERENCES teachers (id),
    CONSTRAINT chk_assignments_due_date CHECK (due_date IS NULL OR due_date >= assigned_date),
    CONSTRAINT chk_assignments_max_score CHECK (max_score IS NULL OR max_score > 0)
);

CREATE INDEX idx_assignments_classroom_id ON assignments (classroom_id);
CREATE INDEX idx_assignments_status ON assignments (status);
CREATE INDEX idx_assignments_due_date ON assignments (due_date);
CREATE INDEX idx_assignments_teacher_id ON assignments (created_by_teacher_id);

CREATE TABLE assignment_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    assignment_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_assignment_targets_assignment FOREIGN KEY (assignment_id) REFERENCES assignments (id),
    CONSTRAINT fk_assignment_targets_student FOREIGN KEY (student_id) REFERENCES students (id),
    CONSTRAINT uk_assignment_targets UNIQUE (assignment_id, student_id)
);

CREATE INDEX idx_assignment_targets_student_id ON assignment_targets (student_id);

CREATE TABLE assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    classroom_id BIGINT NOT NULL,
    class_session_id BIGINT NULL,
    evaluation_period_id BIGINT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT NULL,
    type VARCHAR(30) NOT NULL,
    assessment_date DATE NOT NULL,
    max_score NUMERIC(19, 2) NOT NULL,
    weight NUMERIC(19, 2) NULL,
    status VARCHAR(20) NOT NULL,
    published_to_students BOOLEAN NOT NULL DEFAULT FALSE,
    created_by_teacher_id BIGINT NULL,
    created_by VARCHAR(100) NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT fk_assessments_classroom FOREIGN KEY (classroom_id) REFERENCES classrooms (id),
    CONSTRAINT fk_assessments_session FOREIGN KEY (class_session_id) REFERENCES class_sessions (id),
    CONSTRAINT fk_assessments_period FOREIGN KEY (evaluation_period_id) REFERENCES evaluation_periods (id),
    CONSTRAINT fk_assessments_teacher FOREIGN KEY (created_by_teacher_id) REFERENCES teachers (id),
    CONSTRAINT chk_assessments_max_score CHECK (max_score > 0),
    CONSTRAINT chk_assessments_weight CHECK (weight IS NULL OR weight > 0)
);

CREATE INDEX idx_assessments_classroom_id ON assessments (classroom_id);
CREATE INDEX idx_assessments_status ON assessments (status);
CREATE INDEX idx_assessments_date ON assessments (assessment_date);
CREATE INDEX idx_assessments_period_id ON assessments (evaluation_period_id);
CREATE INDEX idx_assessments_teacher_id ON assessments (created_by_teacher_id);

CREATE TABLE learning_materials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR(255) NOT NULL,
    description TEXT NULL,
    file_name VARCHAR(255) NOT NULL,
    stored_file_name VARCHAR(255) NOT NULL,
